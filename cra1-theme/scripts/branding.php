#!/usr/bin/env php
<?php
/** Regenerate CRA1's original theme-list cover; no customer-side build required. */
declare(strict_types=1);
if(PHP_SAPI!=='cli')exit(1);
$font=$argv[1]??'';
if(!is_file($font))throw new RuntimeException('Pass a Chinese TrueType font path');
$root=dirname(__DIR__,2);$img=imagecreatetruecolor(800,600);
for($y=0;$y<600;$y++)for($x=0;$x<800;$x++){
    $gold=exp(-(($x-650)**2+($y-90)**2)/100000);
    $silver=exp(-(($x-40)**2+($y-570)**2)/90000);
    $rgb=[(int)(26+34*$gold+14*$silver),(int)(29+28*$gold+14*$silver),(int)(34+17*$gold+16*$silver)];
    imagesetpixel($img,$x,$y,imagecolorallocate($img,...$rgb));
}
imageantialias($img,true);
for($i=0;$i<6;$i++)imagearc($img,710,175,665+$i*64,670+$i*60,85,250,imagecolorallocate($img,69+$i*3,66+$i*3,60+$i*3));
imagerectangle($img,66,66,734,534,imagecolorallocate($img,109,103,88));
imagefilledrectangle($img,100,100,184,106,imagecolorallocate($img,212,187,140));
imagettftext($img,86,0,96,258,imagecolorallocate($img,242,239,231),$font,'CRA1');
imagettftext($img,30,0,102,335,imagecolorallocate($img,217,200,165),$font,'酷锐A1主题');
imagettftext($img,17,0,104,412,imagecolorallocate($img,177,181,188),$font,'官网  /  会员中心  /  购物车');
imagettftext($img,13,0,104,494,imagecolorallocate($img,129,134,143),$font,'CRA1 THEME');
$registry=$root.'/cra1-theme/docs/asset-rights.json';$rights=json_decode(file_get_contents($registry),true,512,JSON_THROW_ON_ERROR);
$paths=['public/web/cra1/theme.jpg','public/clientarea/template/pc/cra1/theme.jpg','public/cart/template/pc/cra1/theme.jpg','public/home/template/pc/cra1/theme.jpg'];
foreach($paths as$path){
    imagejpeg($img,$root.'/'.$path,94);
    $rights['assets'][$path]=['sha256'=>hash_file('sha256',$root.'/'.$path),'redistribution'=>'verified',
        'source'=>'CRA1 original artwork generated by cra1-theme/scripts/branding.php',
        'license'=>'Proprietary; see cra1-theme/LICENSE.txt',
        'evidence'=>'Original code-drawn geometric artwork and CRA1 typography; no stock imagery.'];
}
file_put_contents($registry,json_encode($rights,JSON_PRETTY_PRINT|JSON_UNESCAPED_UNICODE|JSON_UNESCAPED_SLASHES)."\n");
echo json_encode(['brand'=>'CRA1','covers'=>count($paths)])."\n";
